"""Archives for the archive tests of the npm package (`tests/npm/test_archives.py`),
generated by the driver and served below `/test-data/`.

* `archive_init.tar.gz`: unpacked by the npm / bundler pages into
  `/unpacked_at_init` (option `archives` of `initializePyjsRuntime`, before
  python starts)
* `archive_runtime.tar.bz2`: unpacked by the test with `pyjs.unpackArchive`

Both contain a python package and a data file in a sub directory, with
directory entries like archives made by `tar` (a different compression each).
"""

import io
import tarfile


def _archive(mode, package, value):
    """a tar archive (mode `w:gz` / `w:bz2`) with `<package>/__init__.py` + `data/info.txt`"""
    buf = io.BytesIO()
    files = {
        f"{package}/__init__.py": f"VALUE = {value!r}\n".encode(),
        "data/info.txt": f"{package}\n".encode(),
    }
    with tarfile.open(fileobj=buf, mode=mode) as tar:
        for directory in sorted({path.split("/")[0] for path in files}):
            info = tarfile.TarInfo(directory)
            info.type = tarfile.DIRTYPE
            info.mode = 0o755
            tar.addfile(info)
        for path, data in sorted(files.items()):
            info = tarfile.TarInfo(path)
            info.size = len(data)
            info.mode = 0o644
            tar.addfile(info, io.BytesIO(data))
    return buf.getvalue()


def build():
    """{url path: bytes} of the test archives"""
    return {
        "/test-data/archive_init.tar.gz": _archive("w:gz", "unpacked_init_pkg", "init"),
        "/test-data/archive_runtime.tar.bz2": _archive("w:bz2", "unpacked_runtime_pkg", "runtime"),
    }
