async def test_jspi_no_run_sync_in_sync_js_callback():
    if not pyjs.jspi_enabled():
        return
    # a JS frame between the promising entry and python: no suspending
    assert not _call_from_sync_js(pyjs.can_run_sync)
    # and back in the task it works again
    assert pyjs.can_run_sync()


async def test_jspi_nested_run_sync():
    if not pyjs.jspi_enabled():
        return
    # while this task is suspended, the coroutine runs as another task, which
    # can suspend in turn (several suspended stacks at once)

    async def inner():
        await asyncio.sleep(0)
        assert pyjs.can_run_sync()
        return pyjs.run_sync(_delayed_promise("inner", 1))

    assert pyjs.run_sync(inner()) == "inner"
    assert pyjs.can_run_sync()


async def test_jspi_concurrent_tasks():
    if not pyjs.jspi_enabled():
        return
    seen = []
    # the waiter's promise is resolved by the other task after its steps, so
    # the order does not depend on timing (slow CI browsers)
    deferred = js.Function(
        "let resolve; const p = new Promise((r) => { resolve = r; }); return [p, resolve];"
    )()
    promise, resolve = deferred[0], deferred[1]

    async def waiter():
        seen.append(("waiter start", pyjs.can_run_sync()))
        value = pyjs.run_sync(promise)
        seen.append(("waiter end", value))

    async def other():
        for i in range(3):
            await asyncio.sleep(0)
            # waiter is suspended: this task can suspend as well
            seen.append((f"other {i}", pyjs.run_sync(js.Promise.resolve(i))))
        resolve("w")

    await asyncio.gather(waiter(), other())
    assert seen[0] == ("waiter start", True), seen
    assert seen[-1] == ("waiter end", "w"), seen
    others = [s for s in seen if s[0].startswith("other")]
    assert others == [("other 0", 0), ("other 1", 1), ("other 2", 2)], seen
    assert pyjs.can_run_sync()


async def test_jspi_run_sync_keeps_context():
    if not pyjs.jspi_enabled():
        return
    import contextvars

    cv = contextvars.ContextVar("cv")
    cv.set("task")

    # a synchronous JS -> python entry while this task is suspended
    # (like a kernel handling the next execute_request)
    def reentrant():
        cv.set("reentrant")

    js_callable = pyjs.create_once_callable(reentrant)
    js.setTimeout(js_callable, 0)
    pyjs.run_sync(_delayed_promise(None, 50))
    assert cv.get() == "task", cv.get()


async def test_jspi_run_sync_keeps_context_deterministic():
    if not pyjs.jspi_enabled():
        return
    import contextvars

    cv = contextvars.ContextVar("cv")
    cv.set("task")

    # the promise is resolved by the re-entrant callback itself, so run_sync
    # can only return after the re-entry happened (no timing assumptions)
    deferred = js.Function(
        "let resolve; const p = new Promise((r) => { resolve = r; }); return [p, resolve];"
    )()
    promise, resolve = deferred[0], deferred[1]
    ran = []

    # a synchronous JS -> python entry while this task is suspended
    # (like a kernel handling the next execute_request)
    def reentrant():
        cv.set("reentrant")
        ran.append(True)
        resolve(None)

    js.setTimeout(pyjs.create_once_callable(reentrant), 0)
    pyjs.run_sync(promise)
    assert ran, "re-entrant callback did not run"
    assert cv.get() == "task", cv.get()


